export const runtime = 'edge';
import { NextResponse } from "next/server";
import { validateDevAccess, logSistema } from "@/lib/dev-auth";

export async function POST(request: Request) {
    const { authorized, errorResponse, supabaseAdmin, user } = await validateDevAccess();
    if (!authorized || !supabaseAdmin) return errorResponse;

    try {
        const body = await request.json();
        const { email } = body;

        if (!email) {
            return NextResponse.json({ error: "E-mail obrigatório para impersonation." }, { status: 400 });
        }

        // Generate a magic link for this user
        const { data, error } = await supabaseAdmin.auth.admin.generateLink({
            type: "magiclink",
            email: email,
            options: {
                redirectTo: process.env.NEXT_PUBLIC_SITE_URL ? `${process.env.NEXT_PUBLIC_SITE_URL}/dashboard` : "http://localhost:3000/dashboard",
            }
        });

        if (error) {
            return NextResponse.json({ error: error.message }, { status: 500 });
        }

        await logSistema(
            supabaseAdmin,
            "IMPERSONATION",
            "WARNING",
            `Impersonation link gerado para ${email}.`,
            { target_email: email, dev_email: user?.email }
        );

        // The URL generated bypasses email sending and can be used directly
        return NextResponse.json({ url: data.properties.action_link });
    } catch (err: any) {
        return NextResponse.json({ error: err.message }, { status: 500 });
    }
}
